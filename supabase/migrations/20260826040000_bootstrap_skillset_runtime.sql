create or replace function public.skillset_estimated_storage_bytes()
returns bigint language sql security definer set search_path to 'skillset','public' as $function$
 select coalesce(sum(x.compressed_bytes),0)::bigint from (select distinct on(content_object_key) content_object_key,compressed_bytes from skillset.skills where content_object_key is not null and compressed_bytes is not null order by content_object_key) x;
$function$;
create or replace function public.skillset_storage_has_capacity(p_limit_bytes bigint default 850000000)
returns boolean language sql security definer set search_path to 'public','skillset' as $function$ select public.skillset_estimated_storage_bytes()<p_limit_bytes;$function$;

create or replace function public.skillset_claim_repository()
returns table(source text,owner text,repo text) language plpgsql security definer set search_path to 'skillset','public' as $function$
begin return query with picked as (select r.source from skillset.repositories r where r.discovery_status in ('pending','retry') or (r.discovery_status='processing' and r.updated_at<now()-interval '20 minutes') order by r.attempts,r.source for update skip locked limit 1),claimed as (update skillset.repositories r set discovery_status='processing',attempts=attempts+1,updated_at=now() from picked p where r.source=p.source returning r.source,r.owner,r.repo) select * from claimed;end;$function$;

create or replace function public.skillset_finish_repository(p_source text,p_branch text,p_files integer,p_new integer,p_error text default null)
returns void language plpgsql security definer set search_path to 'skillset','public' as $function$
begin update skillset.repositories set discovery_status=case when p_error is null then 'ok' when attempts>=3 then 'failed' else 'retry' end,default_branch=coalesce(p_branch,default_branch),discovered_skill_files=greatest(discovered_skill_files,coalesce(p_files,0)),new_skills_found=new_skills_found+coalesce(p_new,0),last_error=p_error,last_scanned_at=now(),updated_at=now() where source=p_source;end;$function$;

create or replace function public.skillset_upsert_repo_discovered_skill(p_source text,p_skill_name text,p_repo_path text,p_owner text,p_repo text,p_source_url text,p_sha text,p_raw_bytes integer,p_object_key text,p_gzip_bytes integer)
returns boolean language plpgsql security definer set search_path to 'skillset','public' as $function$
declare v_id text;v_inserted boolean;begin
 select s.id into v_id from skillset.skills s where s.source=p_source and lower(s.skill_name)=lower(p_skill_name) order by case when s.id=p_source||'/'||p_skill_name then 0 else 1 end,s.first_seen_at limit 1;
 if v_id is null then v_id:=p_source||'/@repo/'||trim(both '/' from p_repo_path);end if;
 insert into skillset.skills(id,source,skill_name,owner,repo,source_url,installs,content_sha256,content_bytes,content_object_key,content_encoding,compressed_bytes,storage_backend,retrieval_status,first_seen_at,last_seen_at,retrieved_at,updated_at)
 values(v_id,p_source,p_skill_name,p_owner,p_repo,p_source_url,0,p_sha,p_raw_bytes,p_object_key,'gzip',p_gzip_bytes,'supabase-storage','ok',now(),now(),now(),now())
 on conflict(id) do update set content_sha256=excluded.content_sha256,content_bytes=excluded.content_bytes,content_object_key=excluded.content_object_key,content_encoding='gzip',compressed_bytes=excluded.compressed_bytes,storage_backend='supabase-storage',source_url=excluded.source_url,retrieval_status='ok',retrieval_error=null,last_seen_at=now(),retrieved_at=now(),updated_at=now()
 returning (xmax=0) into v_inserted;return v_inserted;end;$function$;

create or replace function public.skillset_claim_leaderboard_page()
returns integer language plpgsql security definer set search_path to 'skillset','public' as $function$
declare v_state jsonb;v_page integer;begin
 select value into v_state from skillset.crawl_state where key='leaderboard:all-time' for update;
 if v_state is null then v_state:='{"nextPage":0,"status":"pending"}'::jsonb;insert into skillset.crawl_state(key,value) values('leaderboard:all-time',v_state);end if;
 if coalesce(v_state->>'status','')='complete' then return null;end if;
 if coalesce((v_state->>'inProgress')::boolean,false) and coalesce((v_state->>'claimedAt')::timestamptz,now()-interval '1 hour')>now()-interval '5 minutes' then return null;end if;
 v_page:=coalesce((v_state->>'nextPage')::integer,0);v_state:=jsonb_set(jsonb_set(v_state,'{inProgress}','true'::jsonb),'{claimedAt}',to_jsonb(now()));update skillset.crawl_state set value=v_state,updated_at=now() where key='leaderboard:all-time';return v_page;end;$function$;

create or replace function public.skillset_seed_leaderboard_page(p_rows jsonb,p_page integer,p_total integer,p_has_more boolean)
returns integer language plpgsql security definer set search_path to 'public','skillset' as $function$
declare v_count integer;begin
 with n as (select concat_ws('/',r->>'source',r->>'skillId') id,r->>'source' source,coalesce(r->>'name',r->>'skillId') skill_name,coalesce((r->>'installs')::bigint,0) installs from jsonb_array_elements(p_rows) r where coalesce(r->>'source','')<>'' and coalesce(r->>'skillId','')<>''),d as (select distinct on(id)* from n order by id,installs desc)
 insert into skillset.skills(id,source,skill_name,owner,repo,skill_url,source_url,installs,retrieval_status,first_seen_at,last_seen_at,updated_at)
 select id,source,skill_name,case when source like '%/%' then split_part(source,'/',1) end,case when source like '%/%' then split_part(source,'/',2) end,'https://skills.sh/'||id,case when source like '%/%' then 'https://github.com/'||source end,installs,'pending',now(),now(),now() from d
 on conflict(id) do update set installs=excluded.installs,last_seen_at=now(),updated_at=now();get diagnostics v_count=row_count;
 insert into skillset.repositories(source,owner,repo) select distinct r->>'source',split_part(r->>'source','/',1),split_part(r->>'source','/',2) from jsonb_array_elements(p_rows) r where coalesce(r->>'source','') like '%/%' on conflict(source) do nothing;
 insert into skillset.owner_search(owner) select distinct split_part(r->>'source','/',1) from jsonb_array_elements(p_rows) r where coalesce(r->>'source','') like '%/%' on conflict(owner) do nothing;
 insert into skillset.crawl_state(key,value,updated_at) values('leaderboard:all-time',jsonb_build_object('page',p_page,'nextPage',p_page+1,'total',p_total,'hasMore',p_has_more,'status',case when p_has_more then 'running' else 'complete' end,'inProgress',false),now()) on conflict(key) do update set value=excluded.value,updated_at=excluded.updated_at;return v_count;end;$function$;

create or replace function public.skillset_fail_leaderboard_page(p_page integer,p_error text)
returns void language plpgsql security definer set search_path to 'skillset','public' as $function$
declare v_state jsonb;begin select value into v_state from skillset.crawl_state where key='leaderboard:all-time' for update;if coalesce((v_state->>'nextPage')::integer,-1)=p_page then v_state:=jsonb_set(jsonb_set(v_state,'{inProgress}','false'::jsonb),'{lastError}',to_jsonb(left(p_error,500)));update skillset.crawl_state set value=v_state,updated_at=now() where key='leaderboard:all-time';end if;end;$function$;

