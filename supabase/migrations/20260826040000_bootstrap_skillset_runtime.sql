 on conflict(key) do update set value=excluded.value,updated_at=excluded.updated_at;
$function$;

create or replace function public.skillset_claim_pending(p_limit integer default 50)
returns table(id text,source text,skill_name text,repo text) language plpgsql security definer set search_path to 'skillset','public' as $function$
begin return query
 with picked as (select s.id from skillset.skills s where s.retrieval_status in ('pending','retry') or (s.retrieval_status='processing' and s.updated_at<now()-interval '15 minutes') order by s.first_seen_at,s.id for update skip locked limit greatest(1,least(p_limit,100))),
 claimed as (update skillset.skills s set retrieval_status='processing',updated_at=now() from picked p where s.id=p.id returning s.id,s.source,s.skill_name,s.repo)
 select * from claimed;end;$function$;

create or replace function public.skillset_store_object_content(p_id text,p_content_sha256 text,p_content_bytes integer,p_object_key text,p_compressed_bytes integer,p_source_url text default null,p_backend text default 'supabase-storage')
