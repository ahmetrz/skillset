 select distinct on(s.content_sha256) s.content_sha256,s.skill_md,s.content_bytes from skillset.skills s where s.retrieval_status='ok' and s.skill_md is not null and s.content_sha256 is not null and s.content_object_key is null order by s.content_sha256 limit greatest(1,least(p_limit,250));
$function$;

create or replace function public.skillset_mark_object_stored(p_sha text,p_object_key text,p_compressed_bytes integer,p_backend text default 'supabase-storage')
returns integer language plpgsql security definer set search_path to 'skillset','public' as $function$
