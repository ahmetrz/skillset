create schema if not exists skillset;
create extension if not exists pgcrypto with schema extensions;
create extension if not exists pg_net with schema extensions;
create extension if not exists pg_cron;

create table if not exists skillset.skills (
  id text primary key,
  source text,
  skill_name text,
  description text,
  owner text,
  repo text,
  skill_url text,
  source_url text,
  installs bigint,
  skill_md text,
  content_sha256 text,
  content_bytes integer,
  retrieval_status text not null default 'pending',
  retrieval_error text,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  retrieved_at timestamptz,
  updated_at timestamptz not null default now(),
  content_object_key text,
  content_encoding text,
  compressed_bytes integer,
  storage_backend text
);

create table if not exists skillset.crawl_state (
  key text primary key,
  value jsonb not null,
  updated_at timestamptz not null default now()
);

create table if not exists skillset.repositories (
  source text primary key,
  owner text not null,
  repo text not null,
  discovery_status text not null default 'pending',
  default_branch text,
  discovered_skill_files integer not null default 0,
  new_skills_found integer not null default 0,
  attempts integer not null default 0,
  last_error text,
  last_scanned_at timestamptz,
  updated_at timestamptz not null default now()
);

create table if not exists skillset.owner_search (
  owner text primary key,
  status text not null default 'pending',
  result_count integer,
  saturated boolean not null default false,
  attempts integer not null default 0,
  last_error text,
  searched_at timestamptz,
  updated_at timestamptz not null default now()
);

create table if not exists skillset.job_tokens (
  token uuid primary key,
  purpose text not null,
  expires_at timestamptz not null default (now()+interval '10 minutes'),
  used_at timestamptz
);

create table if not exists skillset.discovery_queue (
  id bigint generated by default as identity primary key,
  kind text not null,
  value text not null,
  status text not null default 'pending',
  attempts integer not null default 0,
  last_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(kind,value)
);

create index if not exists skills_retrieval_status_idx on skillset.skills(retrieval_status);
create index if not exists skills_owner_idx on skillset.skills(owner);
create index if not exists skills_repo_idx on skillset.skills(repo);
create index if not exists idx_skillset_content_hash on skillset.skills(content_sha256);
create index if not exists idx_skillset_object_key on skillset.skills(content_object_key);
create index if not exists discovery_queue_status_idx on skillset.discovery_queue(status,id);

create or replace function public.skillset_consume_job_token(p_token text,p_purpose text)
returns boolean language plpgsql security definer set search_path to 'public','skillset' as $function$
declare v_token uuid;v_count integer:=0;begin
 begin v_token:=p_token::uuid; exception when others then return false; end;
 update skillset.job_tokens set used_at=now() where token=v_token and purpose=p_purpose and used_at is null and expires_at>now();
 get diagnostics v_count=row_count;return v_count=1;
end;$function$;

create or replace function public.skillset_bulk_seed(p_rows jsonb)
returns integer language plpgsql security definer set search_path to 'public','skillset' as $function$
declare v_count integer;begin
 with normalized as (
  select coalesce(r->>'id',concat_ws('/',r->>'source',r->>'skillId')) id,r->>'source' source,
         coalesce(r->>'name',r->>'skillId') skill_name,r->>'owner' owner,r->>'repo' repo,
         coalesce(r->>'skill_url','https://skills.sh/'||(r->>'source')||'/'||(r->>'skillId')) skill_url,
         coalesce(r->>'source_url',r->>'githubUrl') source_url,coalesce((r->>'installs')::bigint,0) installs
  from jsonb_array_elements(p_rows) r where coalesce(r->>'source','')<>'' and coalesce(r->>'skillId','')<>''
 ),deduped as (select distinct on(id)* from normalized order by id,installs desc)
 insert into skillset.skills(id,source,skill_name,owner,repo,skill_url,source_url,installs,retrieval_status,first_seen_at,last_seen_at,updated_at)
 select id,source,skill_name,owner,repo,skill_url,source_url,installs,'pending',now(),now(),now() from deduped
 on conflict(id) do update set installs=greatest(coalesce(skillset.skills.installs,0),excluded.installs),source_url=coalesce(excluded.source_url,skillset.skills.source_url),last_seen_at=now(),updated_at=now();
 get diagnostics v_count=row_count;
 insert into skillset.repositories(source,owner,repo)
 select distinct r->>'source',coalesce(r->>'owner',split_part(r->>'source','/',1)),coalesce(r->>'repo',split_part(r->>'source','/',2))
 from jsonb_array_elements(p_rows) r where coalesce(r->>'source','') like '%/%' on conflict(source) do nothing;
 insert into skillset.owner_search(owner)
 select distinct coalesce(r->>'owner',split_part(r->>'source','/',1)) from jsonb_array_elements(p_rows) r where coalesce(r->>'source','') like '%/%' on conflict(owner) do nothing;
 return v_count;
end;$function$;

